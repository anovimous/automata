-- Baseline schema of Automata, equal to what Hibernate generates from the entities (PostgreSQL),
-- with the changes named "Deviation" below.
--
-- Deviation (http_job): ai_description is varchar(1000) and ai_result varchar(5000) instead of
-- varchar(255); the services reject longer values (HttpJob.MAX_AI_DESCRIPTION_LENGTH and
-- MAX_AI_RESULT_LENGTH).
--
-- Deviation (http_job): Hibernate marks the columns of the NarrowHttpJob subclass (duration, host_id)
-- NOT NULL on the table shared with WideHttpJob, which would reject every wide job. They are nullable
-- here and http_job_narrow_columns_check requires them for narrow jobs only.
--
-- Layout: tables (with primary key, unique, check and identity), then foreign keys.
-- Enum columns are varchar with a check on the enum values; adding or renaming an enum value
-- needs a migration that replaces the matching check. header.location is the only enum stored by
-- ordinal (smallint, no @Enumerated on the field).

CREATE TABLE program (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    insertion_date date NOT NULL,
    link varchar(255),
    name varchar(255) NOT NULL,
    platform varchar(255),
    program_rate_limit integer NOT NULL,
    CONSTRAINT program_pkey PRIMARY KEY (id),
    CONSTRAINT program_platform_check CHECK (platform IN ('BUGCROWD', 'HACKERONE', 'INTIGRITI'))
);

