-- Single table of NarrowHttpJob and WideHttpJob. type is the discriminator: the entity name.
CREATE TABLE http_job (
    type varchar(31) NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ai_description varchar(1000),
    ai_result varchar(5000),
    approved boolean NOT NULL,
    created_by varchar(255) NOT NULL,
    creation_date timestamp(6) with time zone NOT NULL,
    config_file_attempts integer NOT NULL,
    config_file_failure varchar(255),
    config_file_status varchar(255) NOT NULL,
    current_state varchar(255) NOT NULL,
    custom_config jsonb,
    generic_config jsonb,
    http_job_scope varchar(255) NOT NULL,
    last_worker_contact_at timestamp(6) with time zone,
    priority integer NOT NULL,
    rate integer NOT NULL,
    requested_state varchar(255),
    target_selector jsonb,
    verbosity varchar(255) NOT NULL,
    failure_msg varchar(255),
    version bigint,
    duration varchar(255),
    agent_context_id bigint,
    program_id bigint,
    routine_id bigint NOT NULL,
    host_id bigint,
    target_host_id bigint,
    tenant_id bigint,
    CONSTRAINT http_job_pkey PRIMARY KEY (id),
    CONSTRAINT http_job_narrow_columns_check CHECK (type <> 'NarrowHttpJob' OR (duration IS NOT NULL AND host_id IS NOT NULL)),
    CONSTRAINT http_job_config_file_status_check CHECK (config_file_status IN ('PREPARING', 'READY', 'FAILED')),
    CONSTRAINT http_job_created_by_check CHECK (created_by IN ('USER', 'AI')),
    CONSTRAINT http_job_current_state_check CHECK (current_state IN ('DRAFT', 'TOQUEUE', 'SCHEDULED', 'QUEUED', 'RUNNING', 'PAUSED', 'CANCELED', 'FINISHED', 'FAILED', 'SELFTERMINATED', 'LOSTCONTACT')),
    CONSTRAINT http_job_duration_check CHECK (duration IN ('SHORT', 'LONG')),
    CONSTRAINT http_job_http_job_scope_check CHECK (http_job_scope IN ('NARROW', 'WIDE')),
    CONSTRAINT http_job_requested_state_check CHECK (requested_state IN ('DRAFT', 'TOQUEUE', 'SCHEDULED', 'QUEUED', 'RUNNING', 'PAUSED', 'CANCELED', 'FINISHED', 'FAILED', 'SELFTERMINATED', 'LOSTCONTACT')),
    CONSTRAINT http_job_verbosity_check CHECK (verbosity IN ('SUMMARIZED', 'NORMAL', 'VERBOSE'))
);

