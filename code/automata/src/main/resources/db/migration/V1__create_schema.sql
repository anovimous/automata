CREATE TABLE finding (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ai_description text,
    confidence double precision NOT NULL,
    created_by varchar(255) NOT NULL,
    creation_date timestamp(6) with time zone NOT NULL,
    evidence text NOT NULL,
    human_comment text,
    human_verdict varchar(255),
    poc_reproduction_steps text,
    reviewed_at timestamp(6) with time zone,
    severity double precision NOT NULL,
    status varchar(255) NOT NULL,
    agent_context_id bigint,
    host_id bigint NOT NULL,
    job_id bigint,
    request_id bigint NOT NULL,
    vulnerability_id bigint NOT NULL,
    CONSTRAINT finding_pkey PRIMARY KEY (id),
    CONSTRAINT finding_created_by_check CHECK (created_by IN ('AI', 'USER')),
    CONSTRAINT finding_human_verdict_check CHECK (human_verdict IN ('TRUE_POSITIVE', 'FALSE_POSITIVE')),
    CONSTRAINT finding_status_check CHECK (status IN ('SUGGESTED', 'CONFIRMED'))
);

